function assuranceLabel(value, locale = 'ar-SA') {
  if (locale !== 'en' || typeof value !== 'string') return value;
  const key = value.replace(/\s+/g, ' ').trim();
  return Object.hasOwn(EN, key) ? EN[key] : value;
}
function assuranceMoney(value, locale = 'ar-SA', maximumFractionDigits = 2) {
  return Number.isFinite(value)
    ? new Intl.NumberFormat(locale === 'en' ? 'en-US' : 'ar-SA', {maximumFractionDigits}).format(value) + (locale === 'en' ? ' SAR' : ' ر.س')
    : (locale === 'en' ? 'Unavailable' : 'غير متاح');
}
module.exports = {assuranceLabel, assuranceMoney, EN};
