'use strict';

const C2_MARKET_EVIDENCE_SCHEMA_VERSION = 'C2_MARKET_EVIDENCE_V1';

const MARKET_EVIDENCE_TYPE = Object.freeze({
  CLOSED_SALE_TRANSACTION: 'CLOSED_SALE_TRANSACTION',
  CLOSED_RENT_TRANSACTION: 'CLOSED_RENT_TRANSACTION',
  ASKING_SALE_LISTING: 'ASKING_SALE_LISTING',
  ASKING_RENT_LISTING: 'ASKING_RENT_LISTING',
  SALE_PRICE_INDEX: 'SALE_PRICE_INDEX',
  RENT_INDEX: 'RENT_INDEX',
  MARKET_LIQUIDITY_INDICATOR: 'MARKET_LIQUIDITY_INDICATOR',
});

const MARKET_EVIDENCE_CLASS = Object.freeze({
  AUTHORITATIVE_CLOSED_TRANSACTION: 'AUTHORITATIVE_CLOSED_TRANSACTION',
  AUTHORITATIVE_AGGREGATE: 'AUTHORITATIVE_AGGREGATE',
  SUPPLEMENTAL_ASKING: 'SUPPLEMENTAL_ASKING',
});

const MARKET_VERIFICATION_STATUS = Object.freeze({
  VERIFIED: 'VERIFIED',
  UNVERIFIED: 'UNVERIFIED',
  CONFLICTING: 'CONFLICTING',
});

const MARKET_RESOLUTION_METHOD = Object.freeze({
  OFFICIAL_TRANSACTION_RECORD: 'OFFICIAL_TRANSACTION_RECORD',
  OFFICIAL_REGISTERED_CONTRACT: 'OFFICIAL_REGISTERED_CONTRACT',
  OFFICIAL_PUBLISHED_INDICATOR: 'OFFICIAL_PUBLISHED_INDICATOR',
  OFFICIAL_AGGREGATED_MARKET_DATA: 'OFFICIAL_AGGREGATED_MARKET_DATA',
  COMMERCIAL_LISTING: 'COMMERCIAL_LISTING',
  USER_SUPPLIED: 'USER_SUPPLIED',
});

const MARKET_GATE_STATUS = Object.freeze({
  READY: 'READY',
  HOLD_EVIDENCE: 'HOLD_EVIDENCE',
});

const DEFAULT_REQUIRED_MARKET_EVIDENCE_TYPES = Object.freeze([
  MARKET_EVIDENCE_TYPE.CLOSED_SALE_TRANSACTION,
]);

function expectedEvidenceClassForType(evidenceType) {
  switch (evidenceType) {
    case MARKET_EVIDENCE_TYPE.CLOSED_SALE_TRANSACTION:
    case MARKET_EVIDENCE_TYPE.CLOSED_RENT_TRANSACTION:
      return MARKET_EVIDENCE_CLASS.AUTHORITATIVE_CLOSED_TRANSACTION;
    case MARKET_EVIDENCE_TYPE.SALE_PRICE_INDEX:
    case MARKET_EVIDENCE_TYPE.RENT_INDEX:
    case MARKET_EVIDENCE_TYPE.MARKET_LIQUIDITY_INDICATOR:
      return MARKET_EVIDENCE_CLASS.AUTHORITATIVE_AGGREGATE;
    case MARKET_EVIDENCE_TYPE.ASKING_SALE_LISTING:
    case MARKET_EVIDENCE_TYPE.ASKING_RENT_LISTING:
      return MARKET_EVIDENCE_CLASS.SUPPLEMENTAL_ASKING;
    default:
      return null;
  }
}

module.exports = {
  C2_MARKET_EVIDENCE_SCHEMA_VERSION,
  MARKET_EVIDENCE_TYPE,
  MARKET_EVIDENCE_CLASS,
  MARKET_VERIFICATION_STATUS,
  MARKET_RESOLUTION_METHOD,
  MARKET_GATE_STATUS,
  DEFAULT_REQUIRED_MARKET_EVIDENCE_TYPES,
  expectedEvidenceClassForType,
};
