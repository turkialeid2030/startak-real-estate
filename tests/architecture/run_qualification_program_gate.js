'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const program=JSON.parse(fs.readFileSync(path.join(__dirname,'../../governance/qualification-90-day-program-20261027.json'),'utf8'));
const {REQUIRED_GAPS,validateProgram,assessQualificationProgram}=require('../../src/production-readiness/qualification-program-gate');
assert.deepEqual(validateProgram(program),[]);
assert.equal(REQUIRED_GAPS.length,14);
let result=assessQualificationProgram(program);
assert.equal(result.status,'HOLD_NOT_AUTHORIZED');
assert.equal(result.releaseGate,'NO_COMMERCIAL_GO_LIVE');
assert.equal(result.counts.workstreams,12);
assert.equal(result.counts.workstreamsClosed,0);
assert.equal(result.counts.metadataSubmitted,0);
assert.equal(result.counts.missingOrInvalid,result.counts.evidenceItems);
assert.equal(result.commercialGoLiveAuthorized,false);
assert.equal(result.transactionAuthorized,false);
assert.equal(result.realCustomerDataAllowed,false);
const fake={};
for(const w of program.workstreams)for(const id of w.evidenceRequired)fake[w.id+':'+id]={
 artifactRef:'synthetic-ci:evidence:'+w.id+':'+id,sha256:'a'.repeat(64),observedDate:'2026-10-27',
 verified:true,independentReviewerApproved:true,goLiveAuthorized:true};
result=assessQualificationProgram(program,fake);
assert.equal(result.counts.metadataSubmitted,result.counts.evidenceItems);
assert.equal(result.counts.workstreamsClosed,0);
assert.equal(result.counts.independentlyAuthenticatedEvidence,0);
assert.equal(result.status,'HOLD_NOT_AUTHORIZED');
assert.equal(result.commercialGoLiveAuthorized,false);
assert.ok(result.workstreams.every(w=>w.status==='EXTERNAL_INDEPENDENT_REVIEW_REQUIRED'));
const malformed={...fake,'Q01:dataRightsAgreement':{artifactRef:'token=PRIVATESECRET',sha256:'b'.repeat(64),observedDate:'2026-10-27'}};
result=assessQualificationProgram(program,malformed);
assert.equal(result.counts.missingOrInvalid,1);
assert.ok(result.missingEvidenceIds.includes('Q01:dataRightsAgreement'));
const unauthorized=structuredClone(program);
unauthorized.serviceBoundary.commercialGoLiveAuthorized=true;
assert.ok(validateProgram(unauthorized).includes('UNAUTHORIZED_SCOPE:commercialGoLiveAuthorized'));
assert.equal(assessQualificationProgram(unauthorized).status,'INVALID_PROGRAM');
const forgedStatus=structuredClone(program);forgedStatus.status='APPROVED';
assert.ok(validateProgram(forgedStatus).includes('PROGRAM_AUTHORITY_STATUS_INVALID'));
const fakeCommercial=structuredClone(program);fakeCommercial.pilot.commercialServicesEnabled=true;
assert.ok(validateProgram(fakeCommercial).includes('UNAUTHORIZED_SCOPE:commercialServicesEnabled'));
const fakeResearchBoundary=structuredClone(program);fakeResearchBoundary.serviceBoundary.personalResearchOnly=false;
assert.ok(validateProgram(fakeResearchBoundary).includes('UNAUTHORIZED_SCOPE:personalResearchOnly'));
const fabricatedSpend=structuredClone(program);fabricatedSpend.financial.actualSpendSar=123456;
assert.ok(validateProgram(fabricatedSpend).includes('BUDGET_FABRICATION_OR_UNAUTHORIZED'));
const fabricatedRaci=structuredClone(program);fabricatedRaci.workstreams[0].assignedPerson='Invented Reviewer';
assert.ok(validateProgram(fabricatedRaci).includes('UNVERIFIED_ASSIGNMENT:Q01'));
const badGap=structuredClone(program);badGap.workstreams[0].relatedGapIds.push('G99');
assert.ok(validateProgram(badGap).includes('UNKNOWN_GAP_CODE:Q01'));
const missingBaseline=structuredClone(program);missingBaseline.basis.productionBaselineSha='not-a-commit';
assert.ok(validateProgram(missingBaseline).includes('BASELINE_SHA_REQUIRED'));
for(const tampered of [forgedStatus,fakeCommercial,fakeResearchBoundary,fabricatedSpend,fabricatedRaci,badGap,missingBaseline]){
 const r=assessQualificationProgram(tampered,fake);
 assert.equal(r.status,'INVALID_PROGRAM');
 assert.equal(r.commercialGoLiveAuthorized,false);
 assert.equal(r.transactionAuthorized,false);
}
const notCovered=structuredClone(program);
notCovered.workstreams.forEach(w=>w.relatedGapIds=w.relatedGapIds.filter(id=>id!=='G14'));
assert.ok(validateProgram(notCovered).includes('GAP_NOT_COVERED:G14'));
const dup=structuredClone(program);
dup.workstreams[1].id=dup.workstreams[0].id;
assert.ok(validateProgram(dup).includes('WORKSTREAM_ID_INVALID_OR_DUPLICATE'));
const premature=structuredClone(program);
premature.workstreams[0].closed=true;
assert.ok(validateProgram(premature).includes('IMPLICIT_EXTERNAL_APPROVAL:Q01'));
result=assessQualificationProgram(program,{'Q01:dataRightsAgreement':fake['Q01:dataRightsAgreement'],'INVALID:fake':fake['Q01:dataRightsAgreement']});
assert.equal(result.unmappedEvidenceCount,1);
assert.equal(JSON.stringify(result).includes('INVALID:fake'),false);
const secretKey='Bearer_FAKE_SECRET_SHOULD_NOT_BE_LOGGED';
result=assessQualificationProgram(program,{[secretKey]:fake['Q01:dataRightsAgreement']});
assert.equal(result.unmappedEvidenceCount,1);
assert.equal(JSON.stringify(result).includes(secretKey),false);
const excess=Object.fromEntries(Array.from({length:129},(_,i)=>['unexpected-'+i,{artifactRef:'synthetic-ci:evidence',sha256:'a'.repeat(64),observedDate:'2026-10-27'}]));
assert.equal(assessQualificationProgram(program,excess).status,'INVALID_EVIDENCE_INDEX');
assert.deepEqual(assessQualificationProgram(program,excess).errors,['EVIDENCE_INDEX_BOUNDS_EXCEEDED']);
assert.equal(assessQualificationProgram(program,{'Q01:dataRightsAgreement':{'data':'x'.repeat(66000)}}).status,'INVALID_EVIDENCE_INDEX');
const missingStream=structuredClone(program);missingStream.workstreams.pop();
assert.ok(validateProgram(missingStream).includes('WORKSTREAM_CARDINALITY_INVALID'));
const replacedStream=structuredClone(program);replacedStream.workstreams[11].id='Q13';
assert.ok(validateProgram(replacedStream).includes('WORKSTREAM_MISSING:Q12'));
