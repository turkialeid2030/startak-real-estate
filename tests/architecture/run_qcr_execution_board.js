'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const child=require('node:child_process');
const root=path.join(__dirname,'../..');
const program=JSON.parse(fs.readFileSync(path.join(root,'governance/qualification-90-day-program-20261027.json'),'utf8'));
const registry=JSON.parse(fs.readFileSync(path.join(root,'governance/qcr-issue-registry-20261027.json'),'utf8'));
const {board}=require('../../src/production-readiness/qualification-execution-board');
const make=(date='2026-10-27',reg=registry)=>board(program,reg,{asOf:date});
let r=make();
assert.equal(r.status,'HOLD_NOT_AUTHORIZED');
assert.equal(r.totals.streams,12);
assert.equal(r.totals.requiredEvidence,36);
assert.equal(r.totals.independentApprovals,0);
assert.equal(r.totals.streamsClosed,0);
assert.equal(r.rows[0].issueNumber,750);
assert.equal(r.rows[11].issueNumber,761);
assert.ok(r.rows.every(w=>!w.closed&&!w.appointedPersonVerified));
assert.equal(r.rows[0].targetDate,'2026-11-17');
assert.equal(r.rows[11].targetDate,'2027-01-25');
assert.equal(r.totals.targetDatePassed,0);
r=make('2026-11-18');
assert.equal(r.totals.targetDatePassed,1);
assert.equal(r.rows[0].scheduleLabel,'TARGET_PASSED_NOT_EVIDENCE_OF_BREACH');
r=make('2027-01-26');
assert.equal(r.totals.targetDatePassed,12);
assert.equal(r.commercialGoLiveAuthorized,false);
const duplicate=structuredClone(registry);duplicate.mapping[1].issue=750;duplicate.mapping[1].url=duplicate.mapping[0].url;
assert.equal(make('2026-10-27',duplicate).status,'INVALID_ISSUE_REGISTRY');
const missing=structuredClone(registry);missing.mapping.pop();
assert.equal(make('2026-10-27',missing).status,'INVALID_ISSUE_REGISTRY');
const bogus=structuredClone(registry);bogus.mapping[0].url='https://example.test/issues/750';
assert.equal(make('2026-10-27',bogus).status,'INVALID_ISSUE_REGISTRY');
assert.equal(make('2026-02-31').status,'INVALID_REPORT_DATE');
const cli=child.spawnSync(process.execPath,[path.join(root,'tools/qcr-execution-board.js'),'--as-of=2026-10-27','--json'],{encoding:'utf8',timeout:10000});
assert.equal(cli.status,0,cli.stderr);
assert.equal(JSON.parse(cli.stdout).totals.requiredEvidence,36);
const md=child.spawnSync(process.execPath,[path.join(root,'tools/qcr-execution-board.js'),'--as-of=2026-10-27','--markdown'],{encoding:'utf8',timeout:10000});
assert.equal(md.status,0,md.stderr);
assert.ok(md.stdout.includes('Q12')&&md.stdout.includes('HOLD / NOT_AUTHORIZED'));
const invalid=child.spawnSync(process.execPath,[path.join(root,'tools/qcr-execution-board.js'),'--as-of=2026-02-31'],{encoding:'utf8',timeout:10000});
assert.equal(invalid.status,2);
console.log('QCR_EXECUTION_BOARD=PASS workstreams=12 evidence=36 issues=750-761 no_fabricated_signoff=true');
