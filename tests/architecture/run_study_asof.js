'use strict';
const assert=require('node:assert/strict');
const {resolveStudyAsOf,localDateString}=require('../../src/market/study-asof');
const now=new Date(2026,9,28,1,30,0,0);
const today=localDateString(now);
const old=new Date(2026,9,27,0,0,0,0);
const prior=localDateString(old);
const tomorrow=new Date(2026,9,29,0,0,0,0);
const future=localDateString(tomorrow);
const selected=resolveStudyAsOf(today,()=>now);
assert.equal(selected.origin,'USER_VALUATION_DATE');
assert.equal(selected.asOf.getTime(),now.getTime());
assert.equal(selected.date,today);
assert.equal(selected.issues.length,0);
const history=resolveStudyAsOf(prior,()=>now);
assert.equal(history.origin,'USER_VALUATION_DATE');
assert.equal(history.date,prior);
assert.equal(history.asOf.getFullYear(),2026);
assert.equal(history.asOf.getMonth(),9);
assert.equal(history.asOf.getDate(),27);
assert.equal(history.asOf.getHours(),23);
assert.equal(history.asOf.getMinutes(),59);
assert.equal(history.asOf.getSeconds(),59);
const denied=resolveStudyAsOf(future,()=>now);
assert.equal(denied.origin,'FALLBACK_FUTURE_DATE');
assert.equal(denied.issues.includes('FUTURE_VALUATION_DATE_NOT_SUPPORTED'),true);
assert.equal(denied.asOf.getTime(),now.getTime());
const malformed=resolveStudyAsOf('2026-02-30',()=>now);
assert.equal(malformed.origin,'FALLBACK_INVALID_DATE');
assert.equal(malformed.issues.includes('VALUATION_DATE_INVALID'),true);
assert.equal(resolveStudyAsOf('',()=>now).origin,'CURRENT_CLOCK');
const midYear=resolveStudyAsOf('2026-01-01',()=>now);
assert.equal(midYear.date,'2026-01-01');
assert.equal(midYear.asOf.getMonth(),0);
