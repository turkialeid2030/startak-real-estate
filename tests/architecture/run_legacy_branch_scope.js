'use strict';
const assert = require('node:assert/strict');
const {parseBranchAdvertisement, reconcileBranchScope}=require('../../tools/legacy-branch-scope');
const sha='a'.repeat(40), other='b'.repeat(40);
const a={name:'main',sha}, b={name:'new/feature',sha:other};
let checks=0;
const remote=parseBranchAdvertisement(sha+'\trefs/heads/main\n'+other+'\trefs/heads/new/feature\n');
assert.deepEqual(remote,[a,b]); checks++;
const fetched=parseBranchAdvertisement(sha+'\trefs/remotes/origin/HEAD\n'+sha+'\trefs/remotes/origin/main\n'+other+'\trefs/remotes/origin/new/feature\n','refs/remotes/origin/');
assert.deepEqual(fetched,[a,b]); checks++;
const scope=reconcileBranchScope(['main','historical'],remote,fetched);
assert.deepEqual(scope.names,['historical','main','new/feature']); checks++;
assert.equal(scope.baselineCount,2); checks++;
assert.equal(scope.advertisedCount,2); checks++;
assert.equal(scope.newlyDiscoveredCount,1); checks++;
assert.equal(scope.missingBaselineCount,1); checks++;
assert.throws(()=>reconcileBranchScope(['main'],remote,[a]),/BRANCH_SNAPSHOT_CHANGED/); checks++;
assert.throws(()=>reconcileBranchScope(['main'],remote,[a,{...b,sha}]),/BRANCH_SNAPSHOT_CHANGED/); checks++;
assert.throws(()=>reconcileBranchScope(['main'],remote,[a,b,{name:'unexpected',sha}]),/BRANCH_SNAPSHOT_CHANGED/); checks++;
assert.throws(()=>reconcileBranchScope(['main','main'],remote,fetched),/BASELINE_BRANCH_SCOPE_INVALID/); checks++;
assert.throws(()=>reconcileBranchScope(['main'],[a,a],fetched),/BRANCH_SNAPSHOT_INVALID_OR_DUPLICATE/); checks++;
assert.throws(()=>parseBranchAdvertisement(sha+'\trefs/tags/main\n'),/BRANCH_ADVERTISEMENT_INVALID/); checks++;
assert.throws(()=>parseBranchAdvertisement(''),/BRANCH_SNAPSHOT_EMPTY/); checks++;
assert.throws(()=>parseBranchAdvertisement(sha+'\trefs/heads/../bad\n'),/BRANCH_SNAPSHOT_INVALID/); checks++;
assert.throws(()=>reconcileBranchScope([],remote,fetched),/BASELINE_BRANCH_SCOPE_EMPTY/); checks++;
console.log('LEGACY_BRANCH_SCOPE=PASS checks='+checks);
