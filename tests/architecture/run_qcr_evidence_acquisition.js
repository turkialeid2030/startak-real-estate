const {markdown,execute}=require('../../tools/qcr-evidence-acquisition');
let count=0;
const x=makeAcquisitionPack(program,registry,{asOf:'2026-10-28'});
assert.equal(x.status,'REQUEST_PACK_READY_NOT_SENT');count++;
