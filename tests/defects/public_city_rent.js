'use strict';
const assert=require('node:assert/strict');
const {parseCityRent,cityRentSeries}=require('../../src/reporting/public-city-rent');
const ar='السنة,الربع,المنطقة,المدينة,نوع العقار,مجموع الصفقات,المتوسط';
const en='year,quarter,region_ar,city_ar,Category,total_deals,average';
const sample='2019,1,الرياض,الرياض,شقة - سكني,10,20000.25';
const make=(line=sample,header=ar)=>'\uFEFF'+header+'\n'+line+'\n';
const rows=parseCityRent(make(),'الرياض'),scope={region:'الرياض',city:'الرياض',category:'شقة - سكني'};
assert.deepEqual(parseCityRent(make(sample,en),'الرياض'),rows);
assert.equal(rows[0].reportedAverageSar,20000.25);
assert.equal(rows[0].geographyLevel,'CITY');assert.equal(rows[0].propertyEstimateEligible,false);
assert.throws(()=>parseCityRent(make(),'مكة'),/ROW/);
assert.throws(()=>parseCityRent(make(sample.replace('2019','2025')),'الرياض'),/ROW/);
assert.throws(()=>parseCityRent(make(sample.replace(',1,',',5,')),'الرياض'),/ROW/);
assert.throws(()=>parseCityRent(make(sample.replace(',10,',',0,')),'الرياض'),/VALUE/);
assert.throws(()=>parseCityRent(make(sample,'bad'),'الرياض'),/HEADER/);
assert.equal(cityRentSeries(rows,scope)[0].reportedAverageSar,20000.25);
assert.equal(cityRentSeries([...rows,...rows],scope)[0].status,'AMBIGUOUS');
assert.equal(cityRentSeries([{...rows[0],reportedDealCount:1}],scope)[0].reportedAverageSar,null);
assert.equal(cityRentSeries(rows,{...scope,city:'الخرج'}).length,0);
console.log('PUBLIC_CITY_RENT_RULES=PASS cases=12');
