'use strict';
const assert=require('node:assert/strict');
const {KINDS}=require('../../src/reporting/saudi-rental-intelligence');
const {EVIDENCE,specialistReview}=require('../../src/reporting/rental-specialist-review');
assert.deepEqual(Object.keys(EVIDENCE).sort(),[...KINDS].sort());
assert.ok(Object.values(EVIDENCE).every(a=>a.length>=3));
const s=(id,kind,annual,occupancy,collection)=>({id,kind,occupancy,collection,result:{annualRentExVatSar:annual}});
const report={total:{},segments:[s('a','OFFICE',100000,.9,.95),s('b','RETAIL_SHOP',50000,.8,1)]};
const r=specialistReview(report);
assert.equal(r.scenarios.length,4);assert.equal(r.scenarios[0].annual,150000);
assert.equal(r.scenarios[0].collected,125500);
assert.ok(r.scenarios[2].collected<r.scenarios[1].collected&&r.scenarios[1].collected<r.scenarios[0].collected);
assert.ok(r.scenarios[3].collected>r.scenarios[0].collected);
assert.equal(r.financialInputEligible,false);
assert.deepEqual(specialistReview({...report,total:null}).scenarios,[]);
assert.throws(()=>specialistReview({total:{},segments:[s('a','OFFICE',100,-1,1)]}),/SPECIALIST_AMOUNT/);
assert.equal(specialistReview({total:{},segments:[s('a','OFFICE',100,0,0)]}).scenarios[2].collected,0);
assert.equal(specialistReview({total:{},segments:[s('a','OFFICE',100,1,1)]}).scenarios[3].segments[0].occupancy,1);
console.log('RENTAL_SPECIALIST_REVIEW=PASS cases=12 kinds='+KINDS.length);
